"""Wokwi part reference pages for the devices of the experiment 2 modules.

    python -m framework.rag.exp2_device_docs            # writes kb/exp2/devices/<part>.md, updates kb/exp2/SOURCES.md

Pages come from https://github.com/wokwi/wokwi-docs (docs/parts/<part>.md, MIT License): front matter and the
interactive <wokwi-... /> preview tags are removed, the text is kept as is.
"""
from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

import yaml

from framework.common.config import REPO_ROOT

OUT = REPO_ROOT / "kb" / "exp2" / "devices"
RAW = "https://raw.githubusercontent.com/wokwi/wokwi-docs/main/docs/parts/{}.md"
PAGE = "https://docs.wokwi.com/parts/{}"
MARK = "\n## Devices (kb/exp2/devices)\n"


def device_parts() -> list[str]:
    parts = set()
    for path in (REPO_ROOT / "benchmark").glob("*/module.yaml"):
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))
        if meta.get("experiment") == 2:
            parts |= {d["part"] for d in meta.get("devices") or []}
    return sorted(parts)


def clean(md: str) -> str:
    md = re.sub(r"\A---\n.*?\n---\n", "", md, flags=re.S)          # front matter
    md = re.sub(r"<wokwi-[\w-]+[^>]*/>\s*", "", md)                  # interactive preview element
    md = re.sub(r"^import .*$\n?", "", md, flags=re.M)               # MDX imports
    return md.strip() + "\n"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for part in device_parts():
        with urllib.request.urlopen(RAW.format(part), timeout=30) as r:
            text = clean(r.read().decode("utf-8"))
        title = f"# {part} (Wokwi simulator part)\n\n"
        (OUT / f"{part}.md").write_text(f"<!-- source: {PAGE.format(part)} | license: MIT (wokwi-docs) -->\n\n"
                                        + title + text, encoding="utf-8")
        rows.append(part)
        print(part)
    sources = REPO_ROOT / "kb" / "exp2" / "SOURCES.md"
    head = sources.read_text(encoding="utf-8").split(MARK)[0].rstrip("\n") + "\n" if sources.exists() else ""
    table = ["| Part | Source | License |", "|---|---|---|"] + [f"| {p} | {PAGE.format(p)} | MIT |" for p in rows]
    sources.write_text(head + MARK + "\nGenerated by `python -m framework.rag.exp2_device_docs`.\n\n"
                       + "\n".join(table) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
