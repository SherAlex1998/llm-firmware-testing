"""Retrieval check for experiment 2: top-k chunks of kb/.chroma_exp2 for every module.

    python -m framework.rag.exp2_preview       # -> results/exp2/rag_preview.md

A module with a third-party library passes when its top-k contains a chunk about that library.
"""
from __future__ import annotations

import sys
from pathlib import Path

from framework.common.config import load_config, resolve_path
from framework.harness.sketch import load_module_yaml
from framework.rag.exp2_library_docs import slug
from framework.rag.retrieve import retrieve_context
from framework.runner.experiment import OFFICIAL_LIBS

OUT = resolve_path("results/exp2/rag_preview.md")


def library_of(source_path: str) -> str | None:
    """Slug of the library a kb/exp2/libraries/ chunk belongs to."""
    p = Path(source_path)
    if p.parent.name != "libraries" or p.parent.parent.name != "exp2":
        return None
    for suffix in ("_readme", "_api"):
        if p.stem.endswith(suffix):
            return p.stem[: -len(suffix)]
    return p.stem.split("_example_")[0]


def main() -> int:
    cfg = load_config()
    chroma = resolve_path(cfg["experiment2"]["kb_chroma"])
    lines, passed, total = [], 0, 0
    for module in cfg["experiment2"]["modules"]:
        meta = load_module_yaml(resolve_path(f"benchmark/{module}"))
        third = [lib["name"] for lib in meta.get("libraries") or [] if lib["name"] not in OFFICIAL_LIBS]
        res = retrieve_context(module, chroma_path=chroma)
        hit = sorted({library_of(c["source_path"]) for c in res.chunks} & {slug(n) for n in third})
        verdict = "—"
        if third:
            total += 1
            passed += bool(hit)
            verdict = f"ok ({', '.join(hit)})" if hit else "**no chunk of its library**"
        lines += [f"## `{module}` ({meta['complexity']})", "", f"Query: {res.query}", "",
                  f"Third-party libraries: {', '.join(third) or 'none'}; library check: {verdict}", "",
                  "| # | similarity | kind | title | source |", "|---|---|---|---|---|"]
        lines += [f"| {i} | {c['similarity']:.3f} | {c['kind']} | {c['title']} | `{c['source_path']}` |"
                  for i, c in enumerate(res.chunks, 1)]
        lines += ["", f"Context: {len(res.context)} chars (~{len(res.context) // 4} tokens)", ""]
    share = passed / total if total else 1.0
    head = ["# RAG preview, experiment 2", "",
            f"Index `{cfg['experiment2']['kb_chroma']}`, top-k {cfg['rag']['top_k']}, "
            f"max {cfg['rag']['max_context_tokens']} context tokens. Generated by `python -m framework.rag.exp2_preview`.", "",
            f"Modules with a third-party library that have a chunk of it in the top-{cfg['rag']['top_k']}: "
            f"{passed}/{total} ({share:.0%}, target 90%).", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(head + lines), encoding="utf-8")
    print(f"{OUT}: library check {passed}/{total} ({share:.0%})")
    return 0 if share >= 0.9 else 1


if __name__ == "__main__":
    sys.exit(main())
